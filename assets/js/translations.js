function adjustFontSize(element) {
    // Basic auto-scaling: reduce font size if content overflows
    element.style.whiteSpace = 'nowrap'; 
    element.style.overflow = 'hidden'; // Ensure it doesn't spill visually during calc
    
    // Reset to inherited/default first
    element.style.fontSize = '';
    element.style.lineHeight = ''; 
    
    // Get computed style
    const style = window.getComputedStyle(element);
    let size = parseFloat(style.fontSize) || 14; // Default to 14 if null
    
    // Safety break loop
    let iterations = 0;
    
    // Check if content overflows width
    // We add a small buffer (2px) to be safe
    // Also check if text is too long for the container width regardless of scrollWidth sometimes being tricky
    while ((element.scrollWidth > element.clientWidth) && size > 9 && iterations < 20) {
        size--;
        element.style.fontSize = size + 'px';
        // Adjust line-height to center text vertically
        element.style.lineHeight = (size + 1) + 'px'; 
        iterations++;
    }
}

function changeLanguage(lang) {
    if (!translations[lang]) return;

    // Save preference
    localStorage.setItem('selected_language', lang);

    // Update all elements with data-translate attribute
    const elements = document.querySelectorAll('[data-translate]');
    elements.forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang][key]) {
            if (element.tagName === 'INPUT' && element.getAttribute('placeholder')) {
                element.placeholder = translations[lang][key];
            } else {
                const span = element.querySelector('span');
                if (span) {
                    span.innerText = translations[lang][key];
                    // Adjust font size for span parent if needed
                    adjustFontSize(element);
                } else {
                    element.innerText = translations[lang][key];
                    // Adjust font size for element
                    adjustFontSize(element);
                }
            }
        }
    });

    // Update Dropdown Display Text
    const currentText = document.getElementById('currentLang');
    const langNames = {
        'en': 'ENGLISH',
        'fr': 'FRANÇAIS',
        'hi': 'हिन्दी',
        'ta': 'தமிழ்',
        'te': 'తెలుగు',
        'kn': 'ಕನ್ನಡ',
        'mr': 'मराठी',
        'gu': 'ગુજરાતી',
        'bn': 'বাংলা',
        'ml': 'മലയാളം'
    };
    if (currentText && langNames[lang]) {
        currentText.innerText = langNames[lang];
    }

    // Update Popup Dropdown Display Text
    const popupCurrentText = document.getElementById('popupCurrentLang');
    if (popupCurrentText && langNames[lang]) {
        popupCurrentText.innerText = langNames[lang];
    }
    
    // Highlight Active Language in Lists
    const langLists = [document.getElementById('langList'), document.getElementById('popupLangList')];
    langLists.forEach(list => {
        if (list) {
            const items = list.getElementsByTagName('li');
            for (let item of items) {
                item.classList.remove('active-lang');
                if (item.getAttribute('data-lang') === lang) {
                    item.classList.add('active-lang');
                }
            }
        }
    });
    
    // Save to Database if logged in
    if (typeof isLoggedIn !== 'undefined' && isLoggedIn) {
        // Use a more robust path, assuming api is at root/api
        // We can check if we are in admin folder or not, but usually /api/ works if server is configured right.
        // Or relative to current page.
        // If we are at /index.php, 'api/save_language.php' works.
        // If we are at /admin/dashboard.php, it fails.
        // Let's use a variable for base url if available, or try absolute path if we know the domain structure.
        // Since we don't know the domain structure perfectly (could be subdirectory), we'll try to determine it.
        
        let apiUrl = 'api/save_language.php';
        if (window.location.pathname.includes('/admin/')) {
            apiUrl = '../api/save_language.php';
        }
        
        // Better: Use the script path to find the root? No.
        // Let's just use the relative path that works for index.php for now, as that's the main entry.
        // Or if baseUrl is defined in header.
        
        if (typeof baseUrl !== 'undefined') {
            apiUrl = baseUrl + 'api/save_language.php';
        }

        fetch(apiUrl, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json'
            },
            body: JSON.stringify({ lang: lang })
        })
        .then(response => response.json())
        .then(data => {
            if (!data.success) console.error('Failed to save language:', data.message);
        })
        .catch(err => console.error('Error saving language:', err));
    }
}

